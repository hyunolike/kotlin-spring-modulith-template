-- order 모듈의 초기 스키마. 이력은 flyway_schema_history_order 테이블에 따로 기록된다.
-- 스키마는 엔티티 매핑과 1:1로 맞춰야 한다 (spring.jpa.hibernate.ddl-auto=validate가 기동 시 검증).
-- 시각 컬럼은 모두 timestamptz: 애플리케이션은 Instant로 다룬다 (BaseTimeEntity).
-- member_id에는 외래 키를 걸지 않는다: 모듈은 스키마 수준에서도 서로의 테이블에 의존하지 않고,
-- 회원 존재·상태 검증은 MemberApi 파사드가 맡는다.

-- order는 SQL 예약어라 orders
create table orders
(
    id           bigint generated by default as identity primary key,
    member_id    bigint                   not null,
    product_name varchar(255)             not null,
    amount       numeric(15, 2)           not null,
    status       varchar(255)             not null,
    version      bigint                   not null,
    created_at   timestamp with time zone not null,
    updated_at   timestamp with time zone not null,
    constraint ck_orders_status check (status in ('PLACED', 'CANCELLED'))
);

-- findAllByMemberId / findAllByMemberIdAndStatus 조회용 (선두 컬럼 member_id 단독 조회도 커버)
create index idx_orders_member_id_status on orders (member_id, status);
