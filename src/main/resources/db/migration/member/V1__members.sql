-- member 모듈의 초기 스키마. 이력은 flyway_schema_history_member 테이블에 따로 기록된다.
-- 스키마는 엔티티 매핑과 1:1로 맞춰야 한다 (spring.jpa.hibernate.ddl-auto=validate가 기동 시 검증).
-- 시각 컬럼은 모두 timestamptz: 애플리케이션은 Instant로 다룬다 (BaseTimeEntity).

create table members
(
    id         bigint generated by default as identity primary key,
    name       varchar(255)             not null,
    email      varchar(255)             not null,
    status     varchar(255)             not null,
    version    bigint                   not null,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null,
    constraint uk_members_email unique (email),
    constraint ck_members_status check (status in ('ACTIVE', 'DEACTIVATED'))
);
